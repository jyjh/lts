function writeSyntheticReplay(replayCsv, dt, durationS)
% Gentle steer weave at constant speed: enough lateral activity to exercise
% the model, mild enough that free replay stays well behaved. The kinematic
% yaw and lateral channels are consistent with the steer command.
n = round(durationS / dt) + 1;
t = (0:n-1).' * dt;
steer = 0.04 * sin(2 * pi * t / 1.0);
yawRate = 10 * tan(steer) / 1.528;
latG = 10 * yawRate / 9.80665;
T = table(t, t * 10, zeros(n, 1), zeros(n, 1), ...
    -90 * ones(n, 1), 20 * ones(n, 1), steer, 10 * ones(n, 1), ...
    yawRate, latG, ...
    'VariableNames', {'time_s', 'distance_m', 'throttle_ratio', ...
    'brake_ratio', 'regen_torque_nm', 'motor_torque_command_nm', ...
    'steer_rad', 'speed_mps', 'yaw_rate_radps', 'lat_accel_g'});
writetable(T, replayCsv);
end

function deleteIfExists(fileName)
if exist(fileName, 'file')
    delete(fileName);
end
end
