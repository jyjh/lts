function testSegmentRunnerRequiresReplayCsv(testCase)
verifyError(testCase, ...
    @() lts.app.run_correlation_segments('ReplayCsv', ''), ...
    'run_correlation_segments:MissingInput');
end

function testSegmentRunnerSplitsSyntheticReplayIntoScoredSegments(testCase)
    assumeTrue(testCase, tireDataAvailable(), 'TTC tire data not present: see src/+lts/+components/+Tire/README.md');
replayCsv = [tempname '.csv'];
cleanup = onCleanup(@() deleteIfExists(replayCsv)); %#ok<NASGU>
writeSyntheticReplay(replayCsv, 0.01, 4.0);

[segments, pooled, outputs] = lts.app.run_correlation_segments( ...
    'ReplayCsv', replayCsv, ...
    'VehicleConfig', @lts.vehicles.R25, ...
    'Track', 'straight10', ...
    'PowertrainMode', 'motor_torque_command', ...
    'Dt', 0.01, ...
    'SegmentLengthS', 1.5, ...
    'SettleWindowS', 0.25, ...
    'ShowProgress', false);

verifyEqual(testCase, outputs.segmentCount, 2, 'AbsTol', 0);
verifyEqual(testCase, outputs.telemetryMode, 'lean');
verifyEqual(testCase, numel(segments), 2, 'AbsTol', 0);
verifyEqual(testCase, segments(1).t0, 0, 'AbsTol', 1e-9);
verifyEqual(testCase, segments(2).t0, 1.5, 'AbsTol', 1e-9);
verifyEqual(testCase, segments(2).t1, 3.0, 'AbsTol', 1e-9);
verifyTrue(testCase, all(strcmp({segments.status}, 'scored')));
verifyEqual(testCase, pooled.scoredSamples, ...
    sum([segments.scoredSamples]), 'AbsTol', 0);
verifyGreaterThan(testCase, pooled.scoredSamples, 0);
verifyFalse(testCase, isnan(pooled.speed_rmse_mps));
verifyFalse(testCase, isnan(pooled.yaw_rmse_radps));
verifyGreaterThan(testCase, pooled.speed_rmse_mps, 0);
end

