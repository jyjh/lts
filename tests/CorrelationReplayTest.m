function track = localCircleTrack(radius, nPoints)
theta = linspace(0, 2*pi, nPoints + 1).';
theta(end) = [];
points = radius * [cos(theta), sin(theta)];
track = lts.components.WaypointTrack(points, ...
    'Width', 5, ...
    'Closed', true, ...
    'Name', 'CorrelationTestCircle');
end

function profile = localProfileWithCourse(distance, course)
n = numel(distance);
profile = lts.correlation.CorrelationReplayProfile( ...
    'Time', (0:n-1).', ...
    'Distance', distance(:), ...
    'Throttle', zeros(n, 1), ...
    'Brake', zeros(n, 1), ...
    'Steer', zeros(n, 1), ...
    'Speed', ones(n, 1), ...
    'GpsCourse', course(:));
end

function point = localTrackPointAtStation(track, station)
points = track.getTrackPoints();
s = lts.components.Track.cumulativeArcLength(points, true);
p = [points; points(1, :)];
station = mod(station, s(end));
point = [ ...
    interp1(s, p(:, 1), station, 'linear'), ...
    interp1(s, p(:, 2), station, 'linear')];
end

function deleteIfExists(fileName)
if exist(fileName, 'file')
    delete(fileName);
end
end

function cleanupCorrelationFiles(replayFile, outputBase)
deleteIfExists(replayFile);
deleteIfExists([outputBase '.csv']);
deleteIfExists([outputBase '.ld']);
end
