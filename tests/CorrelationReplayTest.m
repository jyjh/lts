function testStateInitializerPreservesBoundaryYawAccelerationSign(testCase)
dt = 0.001;
track = lts.components.TestTrack('straight10');
vehicle = lts.vehicle.VehicleManager.fromConfig(lts.vehicles.R25(), track, dt);
time = (0:dt:0.002)';
profile = lts.correlation.CorrelationReplayProfile( ...
    'Time', time, ...
    'Distance', 7.898 * time, ...
    'Throttle', zeros(size(time)), ...
    'Brake', zeros(size(time)), ...
    'Steer', 0.2649 * ones(size(time)), ...
    'Speed', 7.898 * ones(size(time)), ...
    'YawRate', [1.1485; 1.1475; 1.1465], ...
    'LatAccelG', [0.887; 0.888; 0.889], ...
    'FrontLatAccelG', [0.887; 0.888; 0.889], ...
    'RearLatAccelG', [1.068; 1.067; 1.066]);

initialState = lts.correlation.CorrelationStateInitializer.fromReplayProfile( ...
    profile, track, vehicle, ...
    'UseLoggedWheelSpeeds', false, ...
    'InitialTransientWindowS', 0.3);
simulator = lts.simulation.Simulator(vehicle, [], dt);
stateLog = simulator.simulateReplay( ...
    initialState, track, profile, ...
    'ReplayDomain', 'time', ...
    'ReferenceMode', 'free', ...
    'StopAtReplayEnd', true);

expectedCgG = vehicle.staticFrontWeight * 0.887 + ...
    (1 - vehicle.staticFrontWeight) * 1.068;
verifyEqual(testCase, initialState.ay / 9.80665, expectedCgG, 'AbsTol', 1e-9);
verifyLessThan(testCase, stateLog.yawAccel(1), 0);
verifyEqual(testCase, stateLog.frontAxleAy(1) / 9.80665, 0.887, 'AbsTol', 0.08);
verifyEqual(testCase, stateLog.rearAxleAy(1) / 9.80665, 1.068, 'AbsTol', 0.08);
end

