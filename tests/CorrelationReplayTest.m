function testStateInitializerSeedsSideslipFromLoggedYawRate(testCase)
vehicle = lts.vehicle.VehicleManager([], [], [], [], []);
vehicle.wheelbase = 1.6;
vehicle.staticFrontWeight = 0.5;
profile = lts.correlation.CorrelationReplayProfile( ...
    'Time', [0; 1], ...
    'Distance', [0; 10], ...
    'Throttle', [0; 0], ...
    'Brake', [0; 0], ...
    'Steer', [0; 0], ...
    'Speed', [10; 10], ...
    'YawRate', [1; 1]);

stateWithYawRate = lts.correlation.CorrelationStateInitializer.fromReplayProfile( ...
    profile, [], vehicle, 'UseLoggedYawRate', true);
stateWithoutYawRate = lts.correlation.CorrelationStateInitializer.fromReplayProfile( ...
    profile, [], vehicle, 'UseLoggedYawRate', false);

expectedVy = 0.8;
expectedVx = sqrt(10^2 - expectedVy^2);
verifyEqual(testCase, stateWithYawRate.vx, expectedVx, 'AbsTol', 1e-12);
verifyEqual(testCase, stateWithYawRate.vy, expectedVy, 'AbsTol', 1e-12);
verifyEqual(testCase, stateWithYawRate.speed, 10, 'AbsTol', 1e-12);
verifyEqual(testCase, stateWithoutYawRate.vx, 10, 'AbsTol', 1e-12);
verifyEqual(testCase, stateWithoutYawRate.vy, 0, 'AbsTol', 1e-12);
end

