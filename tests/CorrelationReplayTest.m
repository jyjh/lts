function testFreeReplayDoesNotProjectToTrack(testCase)
dt = 0.01;
track = localCircleTrack(20, 40);
track.Width = 2;
profile = lts.correlation.CorrelationReplayProfile( ...
    'Time', (0:dt:0.05).', ...
    'Distance', (0:dt:0.05).' * 2, ...
    'Throttle', zeros(6, 1), ...
    'Brake', zeros(6, 1), ...
    'Steer', zeros(6, 1), ...
    'Speed', 2 * ones(6, 1));
vehicle = lts.vehicle.VehicleManager.fromConfig(lts.vehicles.R25(), track, dt);
simulator = lts.simulation.Simulator(vehicle, [], dt);
initialState = lts.simulation.VehicleState( ...
    'x', 100, ...
    'y', 100, ...
    'yaw', 0, ...
    'speed', 2, ...
    'vx', 2);

[stateLog, lapTime] = simulator.simulateReplay( ...
    initialState, track, profile, ...
    'ReplayDomain', 'time', ...
    'ReferenceMode', 'free', ...
    'SurfaceMu', 1.2, ...
    'StopAtReplayEnd', true);

verifyGreaterThanOrEqual(testCase, lapTime, 0.04);
verifyTrue(testCase, all(stateLog.onTrack));
verifyEqual(testCase, stateLog.trackLimitMargin, zeros(size(stateLog.trackLimitMargin)), ...
    'AbsTol', 1e-12);
verifyLessThan(testCase, max(stateLog.s), 1);
verifyEqual(testCase, stateLog.lateralError, zeros(size(stateLog.lateralError)), ...
    'AbsTol', 1e-12);
end

function track = localCircleTrack(radius, nPoints)
theta = linspace(0, 2*pi, nPoints + 1).';
theta(end) = [];
points = radius * [cos(theta), sin(theta)];
track = lts.components.WaypointTrack(points, ...
    'Width', 5, ...
    'Closed', true, ...
    'Name', 'CorrelationTestCircle');
end

function profile = localProfileWithCourse(distance, course)
