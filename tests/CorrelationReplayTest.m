function testReplayProfileRepairsPowerInconsistentDeliveredRegen(testCase)
rpm = 2000;
omega = rpm * 2 * pi / 60;
profile = lts.correlation.CorrelationReplayProfile( ...
    'Time', [0; 0.01; 0.02; 0.03], ...
    'Throttle', zeros(4, 1), ...
    'Brake', zeros(4, 1), ...
    'Steer', zeros(4, 1), ...
    'Speed', 10 * ones(4, 1), ...
    'RegenTorqueNm', [-100; -100; -100; 0], ...
    'MotorTorqueCommandNm', [-90; -90; -90; 0], ...
    'MotorTorqueDeliveredNm', [10; -20; -80; 10], ...
    'MotorRpm', rpm * ones(4, 1), ...
    'PackVoltageV', 300 * ones(4, 1), ...
    'PackCurrentA', -40 * ones(4, 1));

[repaired, report] = profile.withPowerConservingRegenRepair( ...
    'PackPowerAdvanceS', 0);
minimumTorque = -12000 / omega;

verifyEqual(testCase, repaired.motorTorqueDeliveredNm, ...
    [minimumTorque; minimumTorque; -80; 10], 'AbsTol', 1e-10);
verifyEqual(testCase, profile.motorTorqueDeliveredNm, [10; -20; -80; 10], ...
    'AbsTol', 1e-12);
verifyEqual(testCase, report.status, "ok");
verifyEqual(testCase, report.repairedSampleCount, 2);
verifyEqual(testCase, report.signContradictionSampleCount, 1);
verifyEqual(testCase, report.remainingPowerDeficitSampleCount, 0);
end

