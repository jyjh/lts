function testReplayContinuesOffTrackToReplayEnd(testCase)
dt = 0.01;
track = localCircleTrack(20, 40);
track.Width = 2;
profile = lts.correlation.CorrelationReplayProfile( ...
    'Time', (0:dt:0.05).', ...
    'Distance', (0:dt:0.05).' * 2, ...
    'Throttle', linspace(0.2, 0.7, 6).', ...
    'Brake', zeros(6, 1), ...
    'Steer', zeros(6, 1), ...
    'Speed', 2 * ones(6, 1), ...
    'LatAccelG', linspace(0.1, 0.6, 6).', ...
    'FrontLatAccelG', linspace(0.2, 0.7, 6).', ...
    'RearLatAccelG', linspace(-0.1, 0.4, 6).', ...
    'LongAccelG', linspace(-0.2, 0.3, 6).', ...
    'FrontLongAccelG', linspace(-0.3, 0.2, 6).', ...
    'RearLongAccelG', linspace(-0.4, 0.1, 6).', ...
    'YawRate', linspace(1.0, 1.5, 6).');
vehicle = lts.vehicle.VehicleManager.fromConfig(lts.vehicles.R25(), track, dt);
simulator = lts.simulation.Simulator(vehicle, [], dt);
initialState = lts.simulation.VehicleState( ...
    'x', 100, ...
    'y', 100, ...
    'yaw', 0, ...
    'speed', 2, ...
    'vx', 2);

[stateLog, lapTime] = simulator.simulateReplay( ...
    initialState, track, profile, ...
    'ReplayDomain', 'time', ...
    'StopOnOffTrack', false, ...
    'StopAtTrackEnd', false, ...
    'StopAtReplayEnd', true);

verifyGreaterThanOrEqual(testCase, lapTime, 0.04);
verifyTrue(testCase, any(~stateLog.onTrack));
verifyLessThan(testCase, min(stateLog.trackLimitMargin), 0);
verifyEqual(testCase, stateLog.controlTime, (0:dt:0.04)', 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.controlS, (0:dt:0.04)' * 2, 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayThrottle, linspace(0.2, 0.6, 5)', 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayBrake, zeros(5, 1), 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replaySpeed, 2 * ones(5, 1), 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayLatAccelG, linspace(0.1, 0.5, 5)', 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayFrontLatAccelG, linspace(0.2, 0.6, 5)', 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayRearLatAccelG, linspace(-0.1, 0.3, 5)', 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayLongAccelG, linspace(-0.2, 0.2, 5)', 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayFrontLongAccelG, linspace(-0.3, 0.1, 5)', 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayRearLongAccelG, linspace(-0.4, 0, 5)', 'AbsTol', 1e-12);
verifyEqual(testCase, stateLog.replayYawRate, linspace(1.0, 1.4, 5)', 'AbsTol', 1e-12);
end

