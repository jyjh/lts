function testStateInitializerUsesBoundaryFitAndReconstructsCgAcceleration(testCase)
track = lts.components.TestTrack('straight10');
vehicle = lts.vehicle.VehicleManager.fromConfig(lts.vehicles.R25(), track, 0.001);
profile = lts.correlation.CorrelationReplayProfile( ...
    'Time', [0; 0.25; 0.5; 1.0], ...
    'Distance', [0; 2.5; 5; 10], ...
    'Throttle', [0; 0; 0; 0], ...
    'Brake', [0; 0; 0; 0], ...
    'Steer', [0.1; 0.1; 0.1; 0.1], ...
    'Speed', [10; 10; 10; 10], ...
    'YawRate', [3; 1; 2; 10], ...
    'LatAccelG', [1.5; 0.5; 1.0; 5.0], ...
    'FrontLatAccelG', [1.2; 0.2; 0.8; 5.0], ...
    'RearLatAccelG', [1.8; 0.8; 1.4; 5.0], ...
    'WheelSpeedFL', [10; 10; 10; 10], ...
    'WheelSpeedFR', [10; 10; 10; 10], ...
    'WheelSpeedRL', [10; 10; 10; 10], ...
    'WheelSpeedRR', [10; 10; 10; 10]);

